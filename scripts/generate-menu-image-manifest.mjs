import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const imageRoot = path.join(root, "public", "images", "products");
const menuPath = path.join(root, "src", "app", "data", "morrow-menu-ai.json");
const outputPath = path.join(root, "src", "app", "data", "cashierMenuImages.generated.ts");
const validExtension = /\.(png|jpe?g|webp)$/i;
const excluded = /^(kids?|placeholders?|temp|archive|unused)(?:\b|[_ -])/i;
const categoryRules = {
  burger: { category: "Burgers", menuCategories: ["burger"] },
  pizza: { category: "Pizza", menuCategories: ["pizza"] },
  pasta: { category: "Pasta", menuCategories: ["pasta"] },
  salads: { category: "Bowls", menuCategories: ["healthy_bowl", "salad"] },
  chicken: { category: "Sides", menuCategories: ["side"] },
  coffee: { category: "Drinks", menuCategories: ["hot_drink"] },
  drink: { category: "Drinks", menuCategories: ["cold_drink"] },
  desserts: { category: "Desserts", menuCategories: ["dessert"] },
};
const normalize = value => value.toLowerCase().replace(/\.[^.]+$/, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const title = value => value.replace(/\.[^.]+$/, "").replace(/[-_]+/g, " ").replace(/\s*\(\d+\)$/, "").replace(/\b\w/g, letter => letter.toUpperCase());
const prefixOf = filename => normalize(filename).split("-")[0];

const menu = JSON.parse(await readFile(menuPath, "utf8"));
const files = (await readdir(imageRoot, { withFileTypes: true })).filter(entry => entry.isFile() && validExtension.test(entry.name) && !excluded.test(entry.name)).map(entry => entry.name).sort((a,b)=>a.localeCompare(b,undefined,{numeric:true}));
const menuProducts = menu.products.filter(product => product.category !== "kids_meal");
const entries = files.map(filename => {
  const prefix = prefixOf(filename);
  const rule = categoryRules[prefix];
  return rule ? { id: `${normalize(rule.category)}-${normalize(filename)}`, name: title(filename), category: rule.category, image: `/images/products/${encodeURIComponent(filename)}`, filename, sourcePath: `public/images/products/${filename}`, productId: undefined, needsConfiguration: true } : null;
}).filter(Boolean);

const usedProducts = new Set();
for (const entry of entries) {
  const rule = categoryRules[prefixOf(entry.filename)];
  const candidates = menuProducts.filter(product => rule.menuCategories.includes(product.category) && !usedProducts.has(product.id));
  const filenameKey = normalize(entry.filename);
  const exact = candidates.find(product => normalize(product.id) === filenameKey || normalize(product.name) === filenameKey || normalize(path.basename(product.image || "")) === filenameKey);
  const match = exact ?? candidates[0];
  if (match) { entry.productId = match.id; entry.needsConfiguration = false; usedProducts.add(match.id); }
}

const ids = new Set(); const images = new Set(); const duplicateIds = []; const duplicateImages = [];
for (const entry of entries) { if (ids.has(entry.id)) duplicateIds.push(entry.id); else ids.add(entry.id); if (images.has(entry.image)) duplicateImages.push(entry.image); else images.add(entry.image); }
const missingProductIds = menuProducts.filter(product => !usedProducts.has(product.id)).map(product => product.id);
const unconfigured = entries.filter(entry => entry.needsConfiguration);
const categories = [...new Set(entries.map(entry => entry.category))];
const report = { products: entries.length, uniqueImages: images.size, matchedProducts: usedProducts.size, missingImages: missingProductIds.length, duplicateImageMappings: duplicateImages.length, duplicateIds: duplicateIds.length, unconfiguredImages: unconfigured.length };
for (const productId of missingProductIds) console.warn(`[cashier-menu] Menu product missing image: ${productId}`);
if (duplicateIds.length || duplicateImages.length) console.warn("[cashier-menu] Duplicate mappings", { duplicateIds, duplicateImages });
console.log("Cashier menu image validation:", report);

const source = `// Generated by scripts/generate-menu-image-manifest.mjs. Do not edit manually.\nexport interface MenuImageEntry { id: string; name: string; category: string; image: string; filename: string; sourcePath: string; productId?: string; needsConfiguration: boolean }\nexport const cashierMenuImageManifest = ${JSON.stringify(entries,null,2)} as const satisfies readonly MenuImageEntry[];\nexport const cashierMenuCategories = ${JSON.stringify(categories)} as const;\nexport const cashierMenuImageReport = ${JSON.stringify(report,null,2)} as const;\nexport const cashierMenuProductsMissingImages = ${JSON.stringify(missingProductIds,null,2)} as const;\n`;
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");
